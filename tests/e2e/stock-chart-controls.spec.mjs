test('native wheel or touch pinch zooms the actual chart and dragging moves its selected window', async ({ page, isMobile, context }) => {
  await page.goto('/stock/NVDA')
  const ui = chart(page), canvas = ui.locator('.stock-chart-canvas')
  await expect.poll(() => count(page)).toBe(32)
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox(), x = box.x + box.width * .4, y = box.y + 90
  if (isMobile) {
    const cdp = await context.newCDPSession(page)
    await cdp.send('Input.synthesizePinchGesture', { x, y, scaleFactor: 1.7, gestureSourceType: 'touch', relativeSpeed: 400 })
    await cdp.detach()
  } else { await page.mouse.move(x, y); await page.mouse.wheel(0, -500) }
  await expect.poll(() => count(page)).toBeLessThan(32)
  const before = await ui.locator('.stock-chart-x-labels').textContent()
  if (isMobile) {
    const cdp = await context.newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    for (let i = 1; i <= 6; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + i * 15, y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await cdp.detach()
  } else { await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 100, y, { steps: 6 }); await page.mouse.up() }
  await expect(ui.locator('.stock-chart-x-labels')).not.toHaveText(before)
  if (isMobile) {
    const cdp = await context.newCDPSession(page), priorScroll = await page.evaluate(() => scrollY)
    await cdp.send('Input.synthesizeScrollGesture', { x, y, yDistance: -140, speed: 500, gestureSourceType: 'touch' })
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(priorScroll)
    await cdp.detach()
  }
})
