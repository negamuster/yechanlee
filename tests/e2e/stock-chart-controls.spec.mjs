test('a late VOO response cannot replace the newly selected period comparison', async ({ page }) => {
  state.delay = { symbol: 'VOO', period: '1M' }
  await page.goto('/stock/NVDA')
  const ui = chart(page)
  await ui.getByRole('button', { name: 'VOO 가격 변화 비교', exact: true }).click()
  await expect.poll(() => state.delayed).toBe(1)
  await ui.locator('.stock-periods').getByRole('button', { name: '6M', exact: true }).click()
  await expect(ui.locator('.stock-chart-comparison-readout')).toBeVisible()
  const returns = await ui.locator('.stock-chart-comparison-readout').textContent()
  const lateResponse = page.waitForResponse(response => response.url().includes('ticker=VOO') && response.url().includes('period=1M'))
  state.benchmarkCurrency = 'EUR'; state.release()
  await (await lateResponse).finished()
  await expect(ui.locator('.stock-chart-comparison-readout')).toHaveText(returns)
  await expect(ui.locator('.stock-periods').getByRole('button', { name: '6M', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(ui.locator('.stock-comparison-unavailable')).toHaveCount(0)
})
