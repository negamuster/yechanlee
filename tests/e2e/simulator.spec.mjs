import { test, expect } from '@playwright/test'
import { installStockFixtures } from './stock-fixtures.mjs'

test('simulator handles boundary ages and rejects invalid ages without blocking input', async ({ page }) => {
  const state = await installStockFixtures(page)
  await page.goto('/simulator')
  const age = page.getByRole('spinbutton', { name: '현재 나이', exact: true })
  await age.fill('-1000000000')
  await expect(page.getByRole('alert')).toContainText('0~100의 정수')
  for (const name of ['은행 저축 · 예금 (원)', '연간 평균 소비 (원)', '연 수입 (원)']) await page.getByRole('textbox', { name, exact: true }).fill('0')
  for (const value of ['0', '25', '100']) {
    await age.fill(value)
    await expect(page.locator('.sim-table tbody tr')).toHaveCount(101 - Number(value))
    await expect(page.locator('.sim-table tbody tr').first().getByRole('rowheader')).toHaveText(`${value}세`)
    await expect(page.locator('.sim-chart text').filter({ hasText: /^\d+세$/ }).first()).toHaveText(`${value}세`)
    await expect(page.locator('.sim-chart text').filter({ hasText: /^100세$/ })).toHaveCount(1)
    await expect(page.locator('.sim-chart-value')).toHaveText('0원')
    const slider = page.getByRole('slider', { name: '차트에서 확인할 나이' })
    if (value === '100') await expect(slider).toBeDisabled()
    else await expect(slider).toBeEnabled()
  }
  for (const value of ['-1000000000', '101', '25.5']) {
    await age.fill(value)
    await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.locator('.sim-chart, .sim-table')).toHaveCount(0)
  }
  await age.fill('25')
  await expect(page.locator('.sim-table tbody tr')).toHaveCount(76)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(state.pageErrors).toEqual([])
})

test('simulator chart selects exact net worth across retirement and negative balances', async ({ page }, testInfo) => {
  const state = await installStockFixtures(page)
  await page.goto('/simulator')
  for (const [name, value] of [['현재 나이', '98'], ['은퇴 나이', '99']]) await page.getByRole('spinbutton', { name, exact: true }).fill(value)
  for (const [name, value] of [['은행 저축 · 예금 (원)', '10000000'], ['연간 평균 소비 (원)', '20000000'], ['연 수입 (원)', '10000000'], ['기타 대출 (원)', '3000000']]) await page.getByRole('textbox', { name, exact: true }).fill(value)
  const chart = page.locator('.simulator-chart'), value = chart.locator('.sim-chart-value')
  const slider = page.getByRole('slider', { name: '차트에서 확인할 나이' })
  await expect(value).toHaveText('-23,000,000원')
  await expect(chart.locator('.sim-chart-breakdown dd')).toHaveText(['0원', '3,000,000원', '20,000,000원'])
  await expect(chart.locator('.sim-retirement-marker')).toContainText('은퇴 99세')
  await slider.focus()
  await slider.press('Home')
  await expect(slider).toHaveValue('98')
  await expect(value).toHaveText('7,000,000원')
  await slider.press('ArrowRight')
  await expect(slider).toHaveValue('99')
  await expect(value).toHaveText('-3,000,000원')
  await expect(page.locator('.sim-table tbody tr').nth(1).locator('td').last()).toHaveText('-3,000,000')
  const bounds = await chart.locator('svg').boundingBox()
  await chart.locator('svg').click({ position: { x: bounds.width - 20, y: bounds.height / 2 } })
  await expect(value).toHaveText('-23,000,000원')
  await expect(chart.locator('svg')).toHaveAccessibleName(/연초 순자산 추이/)
  expect(await chart.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('spinbutton', { name: '현재 나이', exact: true }).fill('100')
  await expect(slider).toBeDisabled()
  await expect(value).toHaveText('7,000,000원')
  await expect(chart.locator('.sim-retirement-marker')).toHaveCount(0)
  await expect(chart.locator('svg')).not.toHaveAttribute('viewBox', /NaN|Infinity/)
  await chart.screenshot({ path: testInfo.outputPath('screen-review-simulator-boundary.png') })
  expect(state.pageErrors).toEqual([])
})

test('simulator chart remains legible at desktop and mobile widths', async ({ page }, testInfo) => {
  await installStockFixtures(page)
  await page.goto('/simulator')
  await page.getByRole('spinbutton', { name: '현재 나이', exact: true }).fill('25')
  await page.getByRole('spinbutton', { name: '은퇴 나이', exact: true }).fill('60')
  await page.getByRole('spinbutton', { name: '예금 연 수익률 (%)', exact: true }).fill('3')
  for (const [name, value] of [['은행 저축 · 예금 (원)', '100000000'], ['연간 평균 소비 (원)', '30000000'], ['연 수입 (원)', '50000000']]) await page.getByRole('textbox', { name, exact: true }).fill(value)
  const chart = page.locator('.simulator-chart')
  await expect(chart.locator('.sim-retirement-marker')).toBeVisible()
  await page.getByRole('slider', { name: '차트에서 확인할 나이' }).focus()
  await page.getByRole('slider', { name: '차트에서 확인할 나이' }).press('Home')
  await expect(chart.locator('.sim-chart-value')).toHaveText('100,000,000원')
  await chart.screenshot({ path: testInfo.outputPath('screen-review-simulator.png') })
  await page.getByRole('spinbutton', { name: '은퇴 나이', exact: true }).fill('99')
  const label = await chart.locator('.sim-retirement-marker text').boundingBox()
  const canvas = await chart.locator('svg').boundingBox()
  expect(label.x).toBeGreaterThanOrEqual(canvas.x)
  expect(label.x + label.width).toBeLessThanOrEqual(canvas.x + canvas.width)
})
