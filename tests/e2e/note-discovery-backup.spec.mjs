test('backup status follows the requested payload across reload and same-count prose edits, never failed imports', async ({ page }) => {
  await page.goto('/saved')
  const status = page.getByRole('region', { name: '백업 상태', exact: true })
  await expect(status).toContainText('이 브라우저에 내보내기 요청 기록이 없습니다.')
  await page.getByText('백업 · 다른 기기로 옮기기', { exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '백업 내보내기', exact: true }).click()
  const file = await downloading, bytes = await readFile(await file.path())
  expect(JSON.parse(bytes.toString()).data).toEqual(seed)
  await expect(status).toContainText('현재 저장 내용은 마지막 내보내기 요청 파일에 포함한 내용과 같습니다.')
  const receipt = await page.evaluate(key => localStorage.getItem(key), statusKey)
  expect(Object.keys(JSON.parse(receipt)).sort()).toEqual(['digest', 'requestedAt', 'version'])
  await page.reload()
  await expect(status).toContainText('마지막 내보내기 요청:')
  await expect(status).toContainText('내용과 같습니다.')
  await page.goto('/saved/thesis/SATL')
  await page.getByLabel('근거 1', { exact: true }).fill('Changed without adding a record')
  await page.getByRole('button', { name: '노트 저장', exact: true }).click()
  await page.getByRole('link', { name: '← 저장한 항목', exact: true }).click()
  await expect(status).toContainText('마지막 내보내기 요청 이후 저장 내용이 달라졌습니다.')
  const before = await stored(page)
  await page.getByText('백업 · 다른 기기로 옮기기', { exact: true }).click()
  await page.locator('.saved-backup input[type=file]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.locator('.saved-backup [role=alert]')).toContainText('지원되는 Anthracite 백업 파일이 아닙니다.')
  expect(await stored(page)).toEqual(before)
  expect(await page.evaluate(key => localStorage.getItem(key), statusKey)).toBe(receipt)
})

test('blocked backup-status writes still download a valid file and never claim an up-to-date backup', async ({ page }) => {
  await page.addInitScript(key => { const original = Storage.prototype.setItem; Storage.prototype.setItem = function(k, v) { if (k === key) throw new DOMException('Blocked metadata', 'QuotaExceededError'); return original.call(this, k, v) } }, statusKey)
  await page.goto('/saved')
  await page.getByText('백업 · 다른 기기로 옮기기', { exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '백업 내보내기', exact: true }).click()
  const file = await downloading, bytes = await readFile(await file.path())
  expect(JSON.parse(bytes.toString()).data).toEqual(seed)
  await expect(page.getByRole('alert')).toContainText('내보내기는 요청했지만 요청 기록을 저장하지 못했습니다.')
  await expect(page.getByRole('region', { name: '백업 상태', exact: true })).not.toContainText('내용과 같습니다.')
  expect(await page.evaluate(key => localStorage.getItem(key), statusKey)).toBeNull()
})
